// tools/rig/build-manifest.mjs — enumerate the public bucket's per-combo
// animation library (the parametric rig's SHAPE layer, §18 location 1) and
// write the runtime manifest module. See tools/rig/README.md.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(__dirname, '..', '..');

const BUCKET = 'https://storage.googleapis.com/cheeze-wizards-production';
const CONTRACT = '0x0d8c864da1985525e0af0acbeef6562881827bd5';
const LIST = `https://storage.googleapis.com/storage/v1/b/cheeze-wizards-production/o?prefix=${CONTRACT}/wizard-animations/&maxResults=1000&fields=items(name),nextPageToken`;

async function listAll() {
  const names = [];
  let tok = '';
  do {
    const res = await fetch(LIST + (tok ? `&pageToken=${tok}` : ''));
    if (!res.ok) throw new Error(`bucket listing failed: ${res.status}`);
    const j = await res.json();
    for (const it of j.items || []) names.push(it.name);
    tok = j.nextPageToken || '';
    process.stderr.write('.');
  } while (tok);
  process.stderr.write('\n');
  return names;
}

const names = await listAll();
const keys = names
  .map((n) => n.split('/')[2])
  .filter(Boolean)
  .map((n) => n.replace(/\.json$/, ''));

const STATES = ['idle', 'charge', 'chargeloop', 'attack', 'hit', 'reset', 'cancel', 'win', 'lose', 'draw'];

// Combos: strip the state prefix, dedupe. Affinity capes: kept separately.
const combos = new Set();
const affinity = new Set();
for (const k of keys) {
  if (k.startsWith('affinitycapewin-') || k.startsWith('affinitycapelose-')) { affinity.add(k); continue; }
  const state = k.split('-')[0];
  if (!STATES.includes(state)) continue;
  combos.add(k.slice(state.length + 1));
}

// A combo only enters the runtime pick pool when every one of the ten duel
// states exists for it (no mid-duel 404s) and it parses as the standard
// ELEMENT-power-head-cape-hat-wand shape (special sets — founder / kitty /
// eviltier7 / oddly-fielded — stay listed but are never auto-assigned).
const byComboStateCount = new Map();
for (const k of keys) {
  const state = k.split('-')[0];
  if (!STATES.includes(state)) continue;
  const combo = k.slice(state.length + 1);
  byComboStateCount.set(combo, (byComboStateCount.get(combo) || 0) + 1);
}
const WELL_FORMED = /^(FIRE|WATER|WIND|NEUTRAL)-(\d+)-(head\d+)-(cape\d+)-(hat\d+)-(wand\d+)$/;
// Sets verified to carry NO colour-slot classes (colour baked at export —
// the 2019 marketing wizard's own set). Recolouring them is a no-op, so a
// wizard assigned one would lose its palette identity: never auto-assign.
// (Verified by tools/parity: every OTHER sampled set carries 36-45 slotted
// fills; this is the only known unslotted one.)
const KNOWN_UNSLOTTED = ['NEUTRAL-1-head01-cape01-hat17-wand07'];
const pool = [...combos]
  .filter((c) => byComboStateCount.get(c) === STATES.length && WELL_FORMED.test(c) && !KNOWN_UNSLOTTED.includes(c))
  .sort();
const special = [...combos].filter((c) => !pool.includes(c)).sort();

// Affinity-cape overlays exist per element and power tier; record which.
const affinityTiers = {};
for (const k of affinity) {
  const m = /^affinitycape(win|lose)-([A-Z]+)-(.+)$/.exec(k);
  if (!m) continue;
  const [, kind, element, tier] = m;
  affinityTiers[element] = affinityTiers[element] || { win: [], lose: [] };
  if (!affinityTiers[element][kind].includes(tier)) affinityTiers[element][kind].push(tier);
}
for (const e of Object.keys(affinityTiers)) {
  affinityTiers[e].win.sort((a, b) => (Number(a) || 999) - (Number(b) || 999));
  affinityTiers[e].lose.sort((a, b) => (Number(a) || 999) - (Number(b) || 999));
}

const out = `// app/data/rigManifest.js — GENERATED by tools/rig/build-manifest.mjs.
// The parametric rig's shape library manifest: which per-combo animation
// sets exist in the public production bucket (§18 location 1). A combo key
// is \`<ELEMENT>-<power>-<head>-<cape>-<hat>-<wand>\`; each combo carries all
// ten duel states. Shapes are keyed to the cosmetic combo, never to a
// specific wizard — a wizard's identity is its own colours filling the
// shape's slots (see app/engine/rigRecolor.js). Do not edit by hand.

export const RIG_BUCKET_BASE = '${BUCKET}/${CONTRACT}/wizard-animations';
export const RIG_STATES = ${JSON.stringify(STATES)};
// Reference playback constants (every set in the library): Lottie v5.5.2.
export const RIG_FPS = 30;
export const RIG_WIDTH = 1720;
export const RIG_HEIGHT = 1400;

// Combos eligible for automatic assignment at summon (all ten states
// present, standard field shape). ${pool.length} sets.
export const RIG_COMBOS = ${JSON.stringify(pool, null, 0)};

// Special / partial sets, listed for completeness, never auto-assigned.
export const RIG_SPECIAL_COMBOS = ${JSON.stringify(special, null, 0)};

// Affinity-cape FX overlays (win/lose) available per element and power tier.
export const RIG_AFFINITY_TIERS = ${JSON.stringify(affinityTiers, null, 0)};
`;

fs.writeFileSync(path.join(REPO, 'app', 'data', 'rigManifest.js'), out);
console.log(`combos: ${pool.length} eligible, ${special.length} special; states x combos = ${keys.length}`);
